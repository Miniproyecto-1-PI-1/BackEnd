-- Esquema base (PostgreSQL): las 4 tablas tal como existían antes de las migraciones 001–005.
-- En una base nueva ejecuta este script y después 001…005 en orden; cada uno agrega sus columnas.
-- Refleja los mapeos JPA de entity/ (spring.jpa.hibernate.ddl-auto=validate no crea nada).

-- Organizadores: cada uno ve solo sus eventos, participantes y gestiones.
CREATE TABLE IF NOT EXISTS app_user (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(255) NOT NULL,
    email         varchar(255) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    created_at    timestamp    NOT NULL DEFAULT now(),
    last_login_at timestamp    NOT NULL DEFAULT now()
);

-- Participantes (antes "clientes") de los eventos de un organizador.
CREATE TABLE IF NOT EXISTS client (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint       NOT NULL REFERENCES app_user (id),
    name       varchar(255) NOT NULL,
    phone      varchar(255),
    email      varchar(255),
    created_at timestamp    NOT NULL DEFAULT now(),
    updated_at timestamp    NOT NULL DEFAULT now()
);

-- Eventos. Sin hora, el backend guarda 00:00.
CREATE TABLE IF NOT EXISTS event (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint       NOT NULL REFERENCES app_user (id),
    client_id   bigint       REFERENCES client (id),
    name        varchar(255) NOT NULL,
    description text,
    event_date  date         NOT NULL,
    event_time  time         NOT NULL,
    place       varchar(255) NOT NULL,
    created_at  timestamp    NOT NULL DEFAULT now(),
    updated_at  timestamp    NOT NULL DEFAULT now()
);

-- Gestiones (tareas) de un evento. Las horas estimadas cuentan para el límite diario mientras no estén hechas.
CREATE TABLE IF NOT EXISTS task (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        bigint        NOT NULL REFERENCES event (id),
    name            varchar(255)  NOT NULL,
    description     varchar(255),
    due_date        date          NOT NULL,
    start_time      time,
    end_time        time,
    estimated_hours numeric(10, 2) NOT NULL,
    status          varchar(255)  NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'DONE', 'POSTPONED')),
    created_at      timestamp     NOT NULL DEFAULT now(),
    updated_at      timestamp     NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS client_user_id_idx ON client (user_id);
CREATE INDEX IF NOT EXISTS event_user_id_idx ON event (user_id);
CREATE INDEX IF NOT EXISTS task_event_id_due_date_idx ON task (event_id, due_date);
